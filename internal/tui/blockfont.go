// blankGlyph is used for any rune with no defined glyph (accented letters,
// symbols, etc.) so the banner degrades gracefully instead of breaking.
var blankGlyph = [7]string{"...", "...", "...", "...", "...", "...", "..."}

func glyphFor(r rune) [7]string {
	if g, ok := blockGlyphs[r]; ok {
		return g
	}
	return blankGlyph
}
